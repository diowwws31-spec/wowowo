create table if not exists public.repositories (
  id            bigint generated by default as identity primary key,
  full_name     text not null unique,
  html_url      text,
  description   text,
  owner         text,
  owner_type    text,
  stars         integer default 0,
  forks         integer default 0,
  watchers      integer default 0,
  open_issues   integer default 0,
  language      text,
  topics        text,
  license       text,
  homepage      text,
  default_branch text,
  commit_count  integer,
  languages_list text,
  readme_preview text,
  matched_queries text,
  created_at    date,
  updated_at    date,
  pushed_at     date,
  first_seen_at timestamptz default now(),
  last_seen_at  timestamptz default now(),
  is_new        boolean default true
);

create index if not exists repositories_updated_idx
  on public.repositories (updated_at desc);

create table if not exists public.runs (
  id          bigint generated by default as identity primary key,
  started_at  timestamptz default now(),
  status      text,
  repos_total integer default 0,
  new_count   integer default 0,
  enriched    integer default 0,
  api_calls   integer default 0,
  message     text
);

create index if not exists runs_started_idx
  on public.runs (started_at desc);

-- RLS aktif TANPA policy = semua akses lewat service role (server-side) saja.
-- Browser nggak pernah pegang key Supabase.
alter table public.repositories enable row level security;
alter table public.runs enable row level security;
